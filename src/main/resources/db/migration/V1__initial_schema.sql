-- V1__initial_schema.sql
-- Esquema relacional inicial para o Motor Antifraude (compatível com PostgreSQL e H2)

CREATE TABLE IF NOT EXISTS fraud_analyses (
    id UUID PRIMARY KEY,
    transaction_id VARCHAR(255) NOT NULL,
    customer_id VARCHAR(255) NOT NULL,
    customer_cpf VARCHAR(255) NOT NULL,
    amount DECIMAL(19, 2) NOT NULL,
    payment_method VARCHAR(50) NOT NULL,
    ip_address VARCHAR(100),
    device_fingerprint VARCHAR(255),
    location VARCHAR(255),
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    risk_score INTEGER NOT NULL,
    decision VARCHAR(50) NOT NULL,
    decision_description VARCHAR(500),
    analyzed_at TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_tx_id ON fraud_analyses(transaction_id);
CREATE INDEX IF NOT EXISTS idx_customer_id ON fraud_analyses(customer_id);
CREATE INDEX IF NOT EXISTS idx_analyzed_at ON fraud_analyses(analyzed_at);

CREATE TABLE IF NOT EXISTS executed_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_id UUID,
    rule_name VARCHAR(100) NOT NULL,
    triggered BOOLEAN NOT NULL,
    score_contribution INTEGER NOT NULL,
    reason VARCHAR(500),
    CONSTRAINT fk_executed_rules_analysis FOREIGN KEY (analysis_id) REFERENCES fraud_analyses(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_executed_rules_analysis ON executed_rules(analysis_id);

CREATE TABLE IF NOT EXISTS blacklist (
    id UUID PRIMARY KEY,
    type VARCHAR(50) NOT NULL,
    target_value VARCHAR(255) NOT NULL,
    reason VARCHAR(500) NOT NULL,
    active BOOLEAN NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_blacklist_val_type ON blacklist(type, target_value);

CREATE TABLE IF NOT EXISTS outbox_events (
    id UUID PRIMARY KEY,
    aggregate_type VARCHAR(50) NOT NULL,
    aggregate_id UUID NOT NULL,
    event_type VARCHAR(100) NOT NULL,
    payload TEXT NOT NULL,
    status VARCHAR(20) NOT NULL,
    retry_count INTEGER NOT NULL DEFAULT 0,
    error_message VARCHAR(1000),
    created_at TIMESTAMP NOT NULL,
    processed_at TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_outbox_status_created ON outbox_events(status, created_at);
